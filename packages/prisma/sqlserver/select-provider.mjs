#!/usr/bin/env node
// Writes packages/prisma/provider/selected.ts, which re-exports the provider module for the database
// in DATABASE_PROVIDER ("postgresql" by default, or "sqlserver"). Run as part of `prisma generate`
// (see the generate-schemas script), so a build only bundles the client and driver it uses.
// Both clients are always generated (generate-schemas), so type-checking covers both providers.
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import dotenv from "dotenv";

dotenv.config({ path: path.resolve(import.meta.dirname, "../../../.env"), quiet: true });

const raw = (process.env.DATABASE_PROVIDER || "").trim().toLowerCase();
const provider =
  raw === "" || raw === "postgres" || raw === "postgresql"
    ? "postgresql"
    : raw === "sqlserver" || raw === "mssql"
      ? "sqlserver"
      : null;
if (!provider) {
  console.error(
    `DATABASE_PROVIDER must be "postgresql" or "sqlserver", got "${process.env.DATABASE_PROVIDER}"`
  );
  process.exit(1);
}

const target = path.join(import.meta.dirname, "../provider/selected.ts");
const content =
  "// GENERATED by packages/prisma/sqlserver/select-provider.mjs from DATABASE_PROVIDER. Do not edit or commit.\n" +
  `export * from "./${provider}";\n`;
if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== content) fs.writeFileSync(target, content);

console.log(`Database provider: ${provider}`);
